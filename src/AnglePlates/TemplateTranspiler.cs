using System;
using System.CodeDom.Compiler;
using System.Collections.Generic;
using System.Diagnostics;
using System.Globalization;
using System.IO;
using System.Security;
using System.Text;
using Microsoft.CodeAnalysis.CSharp;
using Microsoft.CodeAnalysis.Text;

namespace SlusserLabs.AnglePlates;

// Emits the C# class for one template and one generation target
internal static class TemplateTranspiler
{
    private const string _tabString = "    ";
    private const string _variablePrefix = "Write((";
    private const string _plainVariablePrefix = "Write(global::System.Convert.ToString(";

    public static string Transpile(
        string path, string filePath, TextLineCollection lines, TemplateTranspilerOptions options, GenerationTarget target, ReadOnlySpan<char> text, List<Token> tokens)
    {
        Debug.Assert(!string.IsNullOrEmpty(path));
        Debug.Assert(!string.IsNullOrEmpty(options.Namespace));
        Debug.Assert(!string.IsNullOrEmpty(options.Type));
        Debug.Assert(!string.IsNullOrEmpty(options.ModelType));
        Debug.Assert(target is GenerationTarget.Text or GenerationTarget.Utf8);

        // The targets differ only in names, the writer type, and how literals are written.
        // Enum names match the base classes, so Text maps to TextTemplate and Utf8 to Utf8Template.
        bool utf8 = target == GenerationTarget.Utf8;
        string typeName = $"{options.Type}{target}Template";
        string description = utf8 ? "A UTF-8 template" : "A text template";
        string writerType = utf8 ? "global::System.Buffers.IBufferWriter<byte>" : "global::System.IO.TextWriter";

        using var source = new StringWriter(new StringBuilder(text.Length), CultureInfo.InvariantCulture);
        using var writer = new IndentedTextWriter(source, _tabString);

        // Blank lines skip the indented writer so they don't pick up trailing indentation
        void WriteBlankLine() => source.WriteLine();

        // A #line file name has no escape sequences, so a path with a quote or line break can't be mapped
        bool mapLines = filePath.IndexOfAny(['"', '\r', '\n']) < 0;

        // Maps the next generated line, from the column after its indentation and prefix, to the token's span in the
        // template so compiler errors in template C# point at the template. The compiler reports a span that starts
        // before that column as the whole token. The end is 1-based and inclusive, which is the 0-based exclusive end.
        // Directives skip the indented writer like blank lines.
        void WriteLineMapping(Token token, int prefixLength)
        {
            if (mapLines)
            {
                var span = lines.GetLinePositionSpan(TextSpan.FromBounds(token.Start, token.End));
                int column = writer.Indent * _tabString.Length + prefixLength + 1;
                source.WriteLine($"#line ({span.Start.Line + 1}, {span.Start.Character + 1}) - ({span.End.Line + 1}, {span.End.Character}) {column} \"{filePath}\"");
            }
        }

        void WriteDefaultLineMapping()
        {
            if (mapLines)
            {
                source.WriteLine("#line default");
            }
        }

        writer.WriteLine(Boilerplate.AutoGeneratedHeader);
        WriteBlankLine();
        writer.WriteLine(Boilerplate.Directives);
        WriteBlankLine();

        // Imports from #using apply to template C# and the model type; emitted support code stays global::-qualified
        if (options.UsingStatements.Count > 0)
        {
            foreach (var usingStatement in options.UsingStatements)
            {
                writer.WriteLine($"using {usingStatement};");
            }

            WriteBlankLine();
        }

        writer.WriteLine($"namespace {options.Namespace};");
        WriteBlankLine();

        // Class declaration, constructor, and the default instance
        writer.WriteLine("/// <summary>");
        writer.WriteLine($"/// {description} that can render the contents of '{SecurityElement.Escape(path)}'.");
        writer.WriteLine("/// </summary>");
        writer.WriteLine($"{options.AccessModifier} partial class {typeName} : global::SlusserLabs.AnglePlates.{target}Template<{options.ModelType}>");
        writer.WriteLine("{");
        writer.Indent++;
        writer.WriteLine("/// <summary>");
        writer.WriteLine($"/// Initializes a new instance of the <see cref=\"{typeName}\" /> class.");
        writer.WriteLine("/// </summary>");
        writer.WriteLine("/// <param name=\"options\">Options for controlling template processing.</param>");
        writer.WriteLine($"public {typeName}(global::SlusserLabs.AnglePlates.TemplateOptions? options = default) : base(options ?? new global::SlusserLabs.AnglePlates.TemplateOptions())");
        writer.WriteLine("{");
        writer.WriteLine("}");
        WriteBlankLine();
        writer.WriteLine("/// <summary>");
        writer.WriteLine("/// Gets a singleton instance of the template with default options.");
        writer.WriteLine("/// </summary>");
        writer.WriteLine($"public static {typeName} Default {{ get; }} = new {typeName}();");
        WriteBlankLine();

        writer.WriteLine("/// <inheritdoc />");
        writer.WriteLine($"public override void Render({options.ModelType} model, {writerType} writer)");
        writer.WriteLine("{");
        writer.Indent++;
        writer.WriteLine($"{options.ModelType} Model = model; // Allows alternate casing");

        // Emit each template token in source order
        for (int i = 0; i < tokens.Count; i++)
        {
            var token = tokens[i];
            var (offset, length) = token.GetOffsetAndLength();
            switch (token.Type)
            {
                case TokenType.Directive:
                case TokenType.Comment:
                    continue;

                case TokenType.Literal:
                    // Escaped openers split literal text into adjacent tokens, so write each run as one literal
                    int runEnd = i + 1;
                    while (runEnd < tokens.Count && tokens[runEnd].Type == TokenType.Literal)
                    {
                        runEnd++;
                    }

                    var literal = runEnd == i + 1 ? text.Slice(offset, length) : ConcatenateLiterals(text, tokens, i, runEnd).AsSpan();

                    // Trim markers on neighboring blocks remove whitespace from the run's edges
                    if (i > 0 && tokens[i - 1].TrimNext)
                    {
                        literal = literal.TrimStart(options.Whitespace.Span);
                    }

                    if (runEnd < tokens.Count && tokens[runEnd].TrimPrevious)
                    {
                        literal = literal.TrimEnd(options.Whitespace.Span);
                    }

                    i = runEnd - 1;
                    if (literal.IsEmpty)
                    {
                        continue;
                    }

                    // UTF-8 literals use u8 strings, which the compiler stores as bytes in the assembly
                    var quoted = SyntaxFactory.Literal(literal.ToString()).ToFullString();
                    WriteBlankLine();
                    writer.WriteLine(utf8 ? $"global::System.Buffers.BuffersExtensions.Write(writer, {quoted}u8);" : $"writer.Write({quoted});");
                    break;

                case TokenType.Variable:
                    if (length == 0)
                    {
                        continue;
                    }

                    var variable = text.Slice(offset, length).ToString();
                    WriteBlankLine();

                    // Text that isn't one complete expression, such as a stray "[[1, 2]]", keeps the plain call so the compiler
                    // still rejects it; the parentheses below would turn it into a tuple that renders
                    if (SyntaxFactory.ParseExpression(variable).ContainsDiagnostics)
                    {
                        WriteLineMapping(token, _plainVariablePrefix.Length);
                        writer.WriteLine($"{_plainVariablePrefix}{variable}, global::System.Globalization.CultureInfo.InvariantCulture), writer);");
                        WriteDefaultLineMapping();
                        break;
                    }

                    // Check for null before converting so every null value reaches NullVariable, not only strings.
                    // The pattern variable evaluates the expression once, unwraps nullable value types, and needs
                    // a per-token suffix because expression variables share the enclosing block's scope.
                    var valueName = $"__anglePlatesValue{i}";
                    var conversion = $"? global::System.Convert.ToString({valueName}, global::System.Globalization.CultureInfo.InvariantCulture) : null, writer);";
                    WriteLineMapping(token, _variablePrefix.Length);
                    writer.WriteLine($"{_variablePrefix}{variable}) is {{ }} {valueName}");

                    // Errors in the conversion, such as a ref struct value that can't be converted, point at the whole
                    // C# variable because the mapping's column is past the end of this line
                    writer.Indent++;
                    WriteLineMapping(token, conversion.Length);
                    writer.WriteLine(conversion);
                    writer.Indent--;
                    WriteDefaultLineMapping();
                    break;

                case TokenType.Code:
                    if (length == 0)
                    {
                        continue;
                    }

                    // Indent around braces as a best-effort guess; it only affects readability
                    var code = text.Slice(offset, length).ToString();
                    WriteBlankLine();
                    if (code.IndexOf('}') >= 0)
                    {
                        writer.Indent--;
                    }

                    WriteLineMapping(token, 0);
                    writer.WriteLine(code);
                    WriteDefaultLineMapping();
                    if (code.IndexOf('{') >= 0)
                    {
                        writer.Indent++;
                    }

                    break;
            }
        }

        // Close the Render method and the class
        writer.Indent--;
        writer.WriteLine("}");
        writer.Indent--;
        writer.WriteLine("}");

        return source.ToString();
    }

    private static string ConcatenateLiterals(ReadOnlySpan<char> text, List<Token> tokens, int start, int end)
    {
        var run = new StringBuilder();
        for (int i = start; i < end; i++)
        {
            var (offset, length) = tokens[i].GetOffsetAndLength();
            run.Append(text.Slice(offset, length).ToString());
        }

        return run.ToString();
    }
}
